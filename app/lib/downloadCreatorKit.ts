type CreatorKitExportData = {
  keyword: string;

  titles: string[];
  hook: string;
  script: string;
  description: string;
  hashtags: string[];
  thumbnailPrompt: string;

  uploadStrategy: string;
  uploadTime: string;
  targetAudience: string;

  seoKeywords: string[];

  pinnedComment: string;
  communityPost: string;

  viralScore: number;

  callToAction?: string;
  shortsScript?: string;
  instagramCaption?: string;
  twitterPost?: string;
};

/* ============================================================
   SAFE HELPERS
============================================================ */

const safeText = (
  value: unknown
): string => {
  if (typeof value !== "string") {
    return "";
  }

  return value.trim();
};

const safeArray = (
  value: unknown
): string[] => {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .filter(
      (item): item is string =>
        typeof item === "string"
    )
    .map((item) => item.trim())
    .filter(Boolean);
};

const safeViralScore = (
  value: unknown
): number => {
  if (
    typeof value !== "number" ||
    !Number.isFinite(value)
  ) {
    return 0;
  }

  return Math.max(
    0,
    Math.min(
      100,
      Math.round(value)
    )
  );
};

const createSection = (
  title: string,
  content: string,
  fallback: string
): string => {
  return `---

## ${title}

${content || fallback}
`;
};

const normalizeHashtags = (
  hashtags: string[]
): string[] => {
  return hashtags
    .map((hashtag) =>
      hashtag.startsWith("#")
        ? hashtag
        : `#${hashtag}`
    )
    .filter(
      (hashtag, index, array) =>
        array.indexOf(hashtag) ===
        index
    );
};

const createSafeFilename = (
  keyword: string
): string => {
  const normalized =
    keyword
      .trim()
      .replace(
        /[^\p{L}\p{N}\-_]+/gu,
        "-"
      )
      .replace(
        /-+/g,
        "-"
      )
      .replace(
        /^-+|-+$/g,
        ""
      )
      .slice(0, 80);

  return (
    normalized ||
    "creator-kit"
  );
};

/* ============================================================
   DOWNLOAD CREATOR KIT
============================================================ */

export function downloadCreatorKit(
  data: CreatorKitExportData
) {
  const keyword =
    safeText(data.keyword) ||
    "creator-kit";

  const titles =
    safeArray(data.titles);

  const hashtags =
    normalizeHashtags(
      safeArray(data.hashtags)
    );

  const seoKeywords =
    safeArray(
      data.seoKeywords
    );

  const hook =
    safeText(data.hook);

  const script =
    safeText(data.script);

  const description =
    safeText(data.description);

  const thumbnailPrompt =
    safeText(
      data.thumbnailPrompt
    );

  const uploadStrategy =
    safeText(
      data.uploadStrategy
    );

  const uploadTime =
    safeText(data.uploadTime);

  const targetAudience =
    safeText(
      data.targetAudience
    );

  const pinnedComment =
    safeText(
      data.pinnedComment
    );

  const communityPost =
    safeText(
      data.communityPost
    );

  const callToAction =
    safeText(
      data.callToAction
    );

  const shortsScript =
    safeText(
      data.shortsScript
    );

  const instagramCaption =
    safeText(
      data.instagramCaption
    );

  const twitterPost =
    safeText(
      data.twitterPost
    );

  const viralScore =
    safeViralScore(
      data.viralScore
    );

  /* ==========================================================
     MARKDOWN DOCUMENT
  ========================================================== */

  const content = `# Benchmark AI — Creator Kit

> AI-powered content production package generated by Benchmark AI.

---

# 📌 Project

## Keyword

${keyword}

## Viral Potential

**${viralScore}/100**

---

# 🎬 CONTENT PRODUCTION

${createSection(
  "🎯 Titles",
  titles.length > 0
    ? titles
        .map(
          (title, index) =>
            `${index + 1}. ${title}`
        )
        .join("\n")
    : "",
  "No titles generated."
)}

${createSection(
  "⚡ Hook",
  hook,
  "No hook generated."
)}

${createSection(
  "📝 Script",
  script,
  "No script generated."
)}

${createSection(
  "🖼️ Thumbnail Prompt",
  thumbnailPrompt,
  "No thumbnail prompt generated."
)}

${createSection(
  "📣 Call To Action",
  callToAction,
  "No CTA generated."
)}

---

# 📱 SHORT-FORM CONTENT

${createSection(
  "🎬 YouTube Shorts Script",
  shortsScript,
  "No Shorts script generated."
)}

${createSection(
  "📸 Instagram Caption",
  instagramCaption,
  "No Instagram caption generated."
)}

${createSection(
  "𝕏 X / Twitter Post",
  twitterPost,
  "No X/Twitter post generated."
)}

---

# 🔎 SEO

${createSection(
  "📄 YouTube Description",
  description,
  "No description generated."
)}

${createSection(
  "#️⃣ Hashtags",
  hashtags.length > 0
    ? hashtags.join(" ")
    : "",
  "No hashtags generated."
)}

${createSection(
  "🔑 SEO Keywords",
  seoKeywords.length > 0
    ? seoKeywords
        .map(
          (keywordItem, index) =>
            `${index + 1}. ${keywordItem}`
        )
        .join("\n")
    : "",
  "No SEO keywords generated."
)}

---

# 🚀 PUBLISHING

${createSection(
  "📈 Upload Strategy",
  uploadStrategy,
  "No upload strategy generated."
)}

${createSection(
  "🕐 Recommended Upload Time",
  uploadTime,
  "No upload time generated."
)}

${createSection(
  "👥 Target Audience",
  targetAudience,
  "No target audience generated."
)}

---

# 💬 ENGAGEMENT

${createSection(
  "📌 Pinned Comment",
  pinnedComment,
  "No pinned comment generated."
)}

${createSection(
  "💬 YouTube Community Post",
  communityPost,
  "No community post generated."
)}

---

# ✅ PRODUCTION CHECKLIST

- [ ] Choose final title
- [ ] Record / generate the Hook
- [ ] Produce the main Script
- [ ] Create the Thumbnail
- [ ] Add CTA
- [ ] Prepare YouTube Description
- [ ] Add SEO Keywords
- [ ] Add Hashtags
- [ ] Prepare Shorts version
- [ ] Prepare Instagram Caption
- [ ] Prepare X/Twitter Post
- [ ] Add Pinned Comment
- [ ] Prepare Community Post
- [ ] Upload at recommended time
- [ ] Review final packaging before publishing

---

# 📊 BENCHMARK AI SIGNAL

**Viral Potential:** ${viralScore}/100

**Keyword:** ${keyword}

---

Generated by **Benchmark AI**
`;

  /* ==========================================================
     CREATE FILE
  ========================================================== */

  const blob =
    new Blob(
      [content],
      {
        type:
          "text/markdown;charset=utf-8",
      }
    );

  const url =
    URL.createObjectURL(blob);

  const anchor =
    document.createElement(
      "a"
    );

  const filename =
    createSafeFilename(
      keyword
    );

  anchor.href = url;

  anchor.download =
    `benchmark-ai-${filename}-creator-kit.md`;

  document.body.appendChild(
    anchor
  );

  anchor.click();

  document.body.removeChild(
    anchor
  );

  /*
   * Give the browser a moment before
   * releasing the object URL.
   */
  window.setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 1000);
}